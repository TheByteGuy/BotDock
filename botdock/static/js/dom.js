const cache = new Map();

/** Returns a new <svg> element for a known icon name. */
export function icon(name, cls = "") {
  let tpl = cache.get(name);
  if (!tpl) {
    const t = document.createElement("template");
    const p = PATHS[name] || "";
    t.innerHTML = p.startsWith("F:")
      ? `<svg class="icon" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true" focusable="false">${p.slice(2)}</svg>`
      : `<svg class="icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${p}</svg>`;
    tpl = t.content.firstElementChild;
    cache.set(name, tpl);
  }
  const svg = tpl.cloneNode(true);
  if (cls) svg.classList.add(...cls.split(" "));
  return svg;
}

